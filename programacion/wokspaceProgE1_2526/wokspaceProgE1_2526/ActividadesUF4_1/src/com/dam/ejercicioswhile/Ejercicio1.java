package com.dam.ejercicioswhile;

public class Ejercicio1 {

	public static void main(String[] args) {
		// * * * * *
		// * * * * *
		// * * * * *
		// * * * * *
		// * * * * *
		
		String linea = "* * * * *";
		
		int repeticiones = 0;
		
		while (repeticiones < 5) {
			System.out.println(linea);
			repeticiones++;
		}

	}

}
