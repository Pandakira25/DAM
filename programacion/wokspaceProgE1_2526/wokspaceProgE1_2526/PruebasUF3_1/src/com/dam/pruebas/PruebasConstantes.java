package com.dam.pruebas;

public class PruebasConstantes {

	// las constantes se definen en las primeras líneas del bloque de la clase
	// Una constante se define igual que una variable añadiendoles las palabras clave static y final
	// las constantes se nombran en MAYÚSCULAS
	static final double PI = 3.14;
	static final int PORCENTAJE_IVA = 21;
	
	public static void main(String[] args) {
		System.out.println("El valor del número pi es " + PI);
		System.out.println("El porcentaje de IVA a aplicar es el " + PORCENTAJE_IVA);
		

	}

}
